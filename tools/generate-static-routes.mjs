import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const publicDir = path.join(root, "public");
const outputFile = path.join(root, "lib", "seo", "static-routes.js");

const EXCLUDED_ROUTES = new Set([
  "/404.html",
  "/add.html",
  "/edit.html"
]);

async function walk(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...await walk(full));
    else files.push(full);
  }
  return files;
}

function toRoute(file) {
  const rel = path.relative(publicDir, file).split(path.sep).join("/");
  if (rel === "index.html") return "/";
  if (rel.endsWith("/index.html")) return `/${rel.slice(0, -"index.html".length)}`;
  return `/${rel}`;
}

function isNoindex(html) {
  const match = html.match(/<meta\b[^>]*\bname=["']robots["'][^>]*>/i)
    || html.match(/<meta\b[^>]*\bcontent=["'][^"']*noindex[^"']*["'][^>]*\bname=["']robots["'][^>]*>/i);
  return Boolean(match && /noindex/i.test(match[0]));
}

function normalizeDate(value = "") {
  const raw = String(value || "").trim();
  if (!raw) return "";
  const match = raw.match(/^(\d{4}-\d{2}-\d{2})/);
  if (!match) return "";
  const date = new Date(`${match[1]}T00:00:00.000Z`);
  return Number.isNaN(date.getTime()) ? "" : match[1];
}

function extractLastmod(html) {
  const candidates = [];

  for (const match of html.matchAll(/"dateModified"\s*:\s*"([^"]+)"/gi)) {
    const normalized = normalizeDate(match[1]);
    if (normalized) candidates.push(normalized);
  }

  for (const match of html.matchAll(/<meta\b[^>]*(?:name|property)=["'](?:article:modified_time|last-modified)["'][^>]*content=["']([^"']+)["'][^>]*>/gi)) {
    const normalized = normalizeDate(match[1]);
    if (normalized) candidates.push(normalized);
  }

  for (const match of html.matchAll(/<meta\b[^>]*content=["']([^"']+)["'][^>]*(?:name|property)=["'](?:article:modified_time|last-modified)["'][^>]*>/gi)) {
    const normalized = normalizeDate(match[1]);
    if (normalized) candidates.push(normalized);
  }

  return candidates.sort().at(-1) || "";
}

const htmlFiles = (await walk(publicDir)).filter((file) => file.endsWith(".html"));
const routes = [];
const routeLastmod = {};
for (const file of htmlFiles) {
  const route = toRoute(file);
  if (EXCLUDED_ROUTES.has(route) || route.startsWith("/admin/") || /^\/naver[a-z0-9]+\.html$/i.test(route)) continue;
  const html = await fs.readFile(file, "utf8");
  if (isNoindex(html)) continue;
  routes.push(route);
  const lastmod = extractLastmod(html);
  if (lastmod) routeLastmod[route] = lastmod;
}

routes.sort((a, b) => a.localeCompare(b, "en"));
const sortedLastmod = Object.fromEntries(
  Object.entries(routeLastmod).sort(([a], [b]) => a.localeCompare(b, "en"))
);
const output = `// AUTO-GENERATED by tools/generate-static-routes.mjs. Do not edit manually.\nexport const STATIC_ROUTES = Object.freeze(${JSON.stringify(routes, null, 2)});\nexport const STATIC_ROUTE_LASTMOD = Object.freeze(${JSON.stringify(sortedLastmod, null, 2)});\n`;
await fs.mkdir(path.dirname(outputFile), { recursive: true });
await fs.writeFile(outputFile, output, "utf8");
console.log(`Generated ${routes.length} indexable static routes -> ${path.relative(root, outputFile)}`);
