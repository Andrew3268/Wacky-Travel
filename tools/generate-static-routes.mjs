import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const publicDir = path.join(root, "public");
const outputFile = path.join(root, "lib", "seo", "static-routes.js");

const EXCLUDED_ROUTES = new Set([
  "/404.html",
  "/add.html",
  "/edit.html"
]);

async function walk(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...await walk(full));
    else files.push(full);
  }
  return files;
}

function toRoute(file) {
  const rel = path.relative(publicDir, file).split(path.sep).join("/");
  if (rel === "index.html") return "/";
  if (rel.endsWith("/index.html")) return `/${rel.slice(0, -"index.html".length)}`;
  return `/${rel}`;
}

function isNoindex(html) {
  const match = html.match(/<meta\b[^>]*\bname=["']robots["'][^>]*>/i)
    || html.match(/<meta\b[^>]*\bcontent=["'][^"']*noindex[^"']*["'][^>]*\bname=["']robots["'][^>]*>/i);
  return Boolean(match && /noindex/i.test(match[0]));
}

const htmlFiles = (await walk(publicDir)).filter((file) => file.endsWith(".html"));
const routes = [];
for (const file of htmlFiles) {
  const route = toRoute(file);
  if (EXCLUDED_ROUTES.has(route) || route.startsWith("/admin/")) continue;
  const html = await fs.readFile(file, "utf8");
  if (isNoindex(html)) continue;
  routes.push(route);
}

routes.sort((a, b) => a.localeCompare(b, "en"));
const output = `// AUTO-GENERATED by tools/generate-static-routes.mjs. Do not edit manually.\nexport const STATIC_ROUTES = Object.freeze(${JSON.stringify(routes, null, 2)});\n`;
await fs.mkdir(path.dirname(outputFile), { recursive: true });
await fs.writeFile(outputFile, output, "utf8");
console.log(`Generated ${routes.length} indexable static routes -> ${path.relative(root, outputFile)}`);
