import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import crypto from 'node:crypto';
import {DatabaseSync} from 'node:sqlite';
import {validateHotelTop5Json} from '../lib/posts/hotel-top5-json.js';
import {renderHotelTop5Layout, buildTop5ItemList} from '../lib/posts/hotel-top5-renderer.js';
import {onRequestPost} from '../functions/api/posts.js';
import {onRequestGet as adminGet, onRequestPut} from '../functions/api/posts/[slug].js';
import {onRequestGet as publicGet} from '../functions/post/[slug].js';
const sample=JSON.parse(readFileSync('tools/fixtures/hotel-top5-osaka.json','utf8'));
assert.equal(validateHotelTop5Json(sample).ok,true);
assert.equal(validateHotelTop5Json({...sample,hotels:sample.hotels.slice(0,4)}).ok,false);
assert.equal(validateHotelTop5Json({...sample,recommendationsByStyle:[{label:'test',hotelIds:['not-real'],reason:'bad'}]}).ok,false);
assert.equal(validateHotelTop5Json({...sample,hotels:sample.hotels.map((h,i)=>i===0?{...h,booking:{url:'javascript:alert(1)',platform:'x'}}:h)}).ok,false);
let html=renderHotelTop5Layout(sample,{canonical:'https://bestayable.com/post/'+sample.slug+'/'});
assert.equal((html.match(/class="bt5-editorial"/g)||[]).length,5);
assert.equal((html.match(/class="bt5-analysis"/g)||[]).length,5);
assert.ok(html.indexOf('bt5-editorial')<html.indexOf('bt5-analysis'));
assert.equal(buildTop5ItemList(sample,'https://bestayable.com/post/'+sample.slug+'/').itemListElement.length,5);
const withMap=structuredClone(sample);
withMap.locationComparison.enabled=true;
withMap.hotels.forEach((h,i)=>{h.hotel.coordinates={lat:34.66+(i*.002),lng:135.50+(i*.002)};});
assert.equal(validateHotelTop5Json(withMap).ok,true);
const mapHtml=renderHotelTop5Layout(withMap,{canonical:'https://bestayable.com/post/map-test/'});
assert.ok(mapHtml.includes('bt5-map-canvas'));

// Exercise actual public + admin APIs against D1-like SQLite adapter.
const sqlite=new DatabaseSync(':memory:');
sqlite.exec(readFileSync('db/schema.sql','utf8'));
const db={prepare(sql){let args=[];return {bind(...v){args=v;return this},async run(){let x=sqlite.prepare(sql).run(...args);return {success:true,meta:{last_row_id:x.lastInsertRowid}}},async first(){return sqlite.prepare(sql).get(...args)||null},async all(){return {results:sqlite.prepare(sql).all(...args)}}}}};
const env={TRAVEL_DB:db,SITE_URL:'https://bestayable.com'};

let token='phase11-test-token',tokenHash=crypto.createHash('sha256').update(token).digest('hex');
sqlite.prepare('INSERT INTO admin_users VALUES(1,?,?,?,?)').run('test@localhost','hash',new Date().toISOString(),new Date().toISOString());
sqlite.prepare('INSERT INTO admin_sessions VALUES(?,?,?,?)').run(tokenHash,1,'2035-01-01T00:00:00.000Z',new Date().toISOString());
const cookies={cookie:'admin_session='+token,'content-type':'application/json'};
const payload={content_type:'top5_series',content_format:'json',content_json:JSON.stringify(sample),status:'published'};
const post=await onRequestPost({env,request:new Request('https://bestayable.com/api/posts',{method:'POST',headers:cookies,body:JSON.stringify(payload)})});
assert.equal(post.status,200,'Create failed: '+await post.text());
const row=sqlite.prepare('SELECT slug,content_json,content_format,hotel_slug FROM posts WHERE slug=?').get(sample.slug);
assert.equal(row.content_format,'json');assert.equal(row.hotel_slug,'');
const fetched=await adminGet({env,params:{slug:sample.slug},request:new Request('https://bestayable.com/api/posts/'+sample.slug,{headers:cookies})});
assert.equal(fetched.status,200);
assert.equal((await fetched.json()).item.content_json.length>10000,true);
const revised=structuredClone(sample);revised.hotels[0].editorial.headline+=' — 테스트';
const update=await onRequestPut({env,params:{slug:sample.slug},request:new Request('https://bestayable.com/api/posts/'+sample.slug,{method:'PUT',headers:cookies,body:JSON.stringify({...payload,content_json:JSON.stringify(revised)})})});
assert.equal(update.status,200,'Update failed: '+await update.text());
assert.ok(sqlite.prepare('SELECT content_json FROM posts WHERE slug=?').get(sample.slug).content_json.includes(' — 테스트'));
const bad=await onRequestPut({env,params:{slug:sample.slug},request:new Request('https://bestayable.com/api/posts/'+sample.slug,{method:'PUT',headers:cookies,body:JSON.stringify({...payload,content_json:JSON.stringify({...sample,hotels:sample.hotels.slice(1)})})})});
assert.equal(bad.status,400);
// Cloudflare cache fixture; ensure public HTML SSR is returned and draft is blocked.
globalThis.caches={default:{async match(){return null},async put(){}}};
const publicReq=new Request('https://bestayable.com/post/'+sample.slug+'/');
const page=await publicGet({env,params:{slug:sample.slug},request:publicReq,waitUntil(){}});
assert.equal(page.status,200,'SSR failed: '+await page.clone().text());
html=await page.text();
assert.ok(html.includes('hotel-top5-public.css'));
assert.ok(html.includes('호텔 5곳 종합 비교'));
assert.ok(html.includes('schema.org')); 
assert.equal((html.match(/class="bt5-editorial"/g)||[]).length,5);
assert.ok(html.includes('ItemList'));
assert.ok(!html.includes('javascript:alert'));
const privateRes=await publicGet({env,params:{slug:sample.slug},request:new Request(publicReq.url+'?preview=1'),waitUntil(){}});
assert.equal(privateRes.status,404);
console.log('[top5 phase11] Schema, create, fetch, update, invalid update, real SQLite and SSR passed');
